const fs = require("fs");
const path = require("path");
const ts = require("../client/node_modules/typescript");

require.extensions[".ts"] = (module, filename) => {
  const source = fs.readFileSync(filename, "utf8");
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      esModuleInterop: true,
    },
    fileName: filename,
  });

  module._compile(compiled.outputText, filename);
};

const market = require("../client/src/data/mockStocks.ts");
const GENERATED_MARKET_DAYS = market.SEASON_LENGTH ?? 30;

function sqlText(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function sqlNumber(value, decimals = 6) {
  return Number(value).toFixed(decimals);
}

const companies = market.mockStockCompanies;
const prices = companies.flatMap((company) =>
  market.getStockHistoryBySymbol(company.symbol, GENERATED_MARKET_DAYS)
);
const eventSeeds = market.getMarketEventSeedsUpToGameDay(GENERATED_MARKET_DAYS);

const stockRows = companies.map((company) => {
  const latest = prices
    .filter((price) => price.symbol === company.symbol)
    .at(-1);
  const fundamentals = company.fundamentals;

  return `  (
    ${sqlText(company.symbol)},
    ${sqlText(company.name)},
    ${sqlText(company.sector)},
    ${sqlText(company.industry)},
    ${sqlText(company.description)},
    ${sqlNumber(company.startingPrice, 2)},
    ${sqlNumber(latest?.closePrice ?? company.startingPrice, 2)},
    ${sqlNumber(company.volatility, 5)},
    ${sqlNumber(company.trendBias, 6)},
    ${sqlText(company.riskLevel)},
    ${sqlNumber(fundamentals.peRatio, 2)},
    ${sqlNumber(fundamentals.eps, 2)},
    ${sqlNumber(fundamentals.revenueGrowth, 2)},
    ${sqlNumber(fundamentals.profitMargin, 2)},
    ${sqlNumber(fundamentals.debtToEquity, 2)},
    ${sqlNumber(fundamentals.dividendYield, 2)},
    ${sqlText(fundamentals.analystRating)},
    ${company.isActive}
  )`;
}).join(",\n");

const priceRows = prices.map((price) => `  (
    ${sqlText(price.symbol)},
    ${price.gameDay},
    ${sqlNumber(price.openPrice, 2)},
    ${sqlNumber(price.highPrice, 2)},
    ${sqlNumber(price.lowPrice, 2)},
    ${sqlNumber(price.closePrice, 2)},
    ${Math.round(price.volume)},
    ${sqlNumber(price.eventImpact, 6)}
  )`).join(",\n");

const eventRows = eventSeeds.map((event) => `  (
    ${sqlText(event.eventKey)},
    ${event.gameDay},
    ${sqlText(event.source)},
    ${sqlText(event.headline)},
    ${sqlText(event.body)},
    ${sqlText(event.importance)},
    ${sqlText(event.category)},
    ${event.isAccurate},
    ${event.isRumor}
  )`).join(",\n");

const impactRows = eventSeeds.flatMap((event) =>
  event.impacts.map((impact) => `  (
    ${sqlText(event.eventKey)},
    ${sqlText(impact.symbol)},
    ${sqlNumber(impact.expectedImpact, 6)},
    ${sqlNumber(impact.actualImpact, 6)}
  )`)
).join(",\n");

const migration = `-- Generated by scripts/generate-market-data-migration.cjs
-- Source: client/src/data/mockStocks.ts

begin;

insert into public.stocks (
  symbol,
  company_name,
  sector,
  industry,
  description,
  initial_price,
  current_price,
  volatility,
  trend_bias,
  risk_level,
  pe_ratio,
  eps,
  revenue_growth,
  profit_margin,
  debt_to_equity,
  dividend_yield,
  analyst_rating,
  is_active
)
values
${stockRows}
on conflict (symbol) do update
set
  company_name = excluded.company_name,
  sector = excluded.sector,
  industry = excluded.industry,
  description = excluded.description,
  initial_price = excluded.initial_price,
  current_price = excluded.current_price,
  volatility = excluded.volatility,
  trend_bias = excluded.trend_bias,
  risk_level = excluded.risk_level,
  pe_ratio = excluded.pe_ratio,
  eps = excluded.eps,
  revenue_growth = excluded.revenue_growth,
  profit_margin = excluded.profit_margin,
  debt_to_equity = excluded.debt_to_equity,
  dividend_yield = excluded.dividend_yield,
  analyst_rating = excluded.analyst_rating,
  is_active = excluded.is_active,
  updated_at = now();

delete from public.stock_prices
where game_day > 0;

insert into public.stock_prices (
  stock_id,
  game_day,
  open_price,
  high_price,
  low_price,
  close_price,
  volume,
  event_impact
)
select
  stocks.id,
  prices.game_day,
  prices.open_price,
  prices.high_price,
  prices.low_price,
  prices.close_price,
  prices.volume,
  prices.event_impact
from (
  values
${priceRows}
) as prices(
  symbol,
  game_day,
  open_price,
  high_price,
  low_price,
  close_price,
  volume,
  event_impact
)
join public.stocks as stocks on stocks.symbol = prices.symbol
on conflict (stock_id, game_day) do update
set
  open_price = excluded.open_price,
  high_price = excluded.high_price,
  low_price = excluded.low_price,
  close_price = excluded.close_price,
  volume = excluded.volume,
  event_impact = excluded.event_impact;

delete from public.market_events;

insert into public.market_events (
  event_key,
  game_day,
  source,
  headline,
  body,
  importance,
  category,
  is_accurate,
  is_rumor
)
values
${eventRows};

insert into public.event_stock_impacts (
  event_id,
  stock_id,
  expected_impact,
  actual_impact
)
select
  events.id,
  stocks.id,
  impacts.expected_impact,
  impacts.actual_impact
from (
  values
${impactRows}
) as impacts(event_key, symbol, expected_impact, actual_impact)
join public.market_events as events on events.event_key = impacts.event_key
join public.stocks as stocks on stocks.symbol = impacts.symbol;

commit;
`;

const output = path.resolve(
  __dirname,
  "../supabase/migrations/202606240004_complete_market_data.sql"
);

fs.writeFileSync(output, migration);

console.log(`Generated ${path.relative(process.cwd(), output)}`);
console.log(`Stocks: ${companies.length}`);
console.log(`Prices: ${prices.length}`);
console.log(`Events: ${eventSeeds.length}`);
console.log(`Impacts: ${eventSeeds.reduce(
  (total, event) => total + event.impacts.length,
  0
)}`);
