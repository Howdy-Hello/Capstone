begin;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  bio text not null default '',
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (
    username is null
    or username ~ '^[A-Za-z0-9_]{3,24}$'
  ),
  constraint profiles_bio_length check (char_length(bio) <= 280)
);

create table if not exists public.stocks (
  id bigint generated by default as identity primary key,
  symbol text not null unique,
  company_name text not null,
  sector text not null,
  industry text not null,
  description text not null default '',
  initial_price numeric(12, 2) not null check (initial_price > 0),
  current_price numeric(12, 2) not null check (current_price > 0),
  volatility numeric(7, 5) not null check (volatility between 0 and 1),
  trend_bias numeric(8, 6) not null default 0,
  risk_level text not null check (risk_level in ('Low', 'Medium', 'High')),
  pe_ratio numeric(10, 2) not null default 0,
  eps numeric(10, 2) not null default 0,
  revenue_growth numeric(8, 2) not null default 0,
  profit_margin numeric(8, 2) not null default 0,
  debt_to_equity numeric(8, 2) not null default 0,
  dividend_yield numeric(8, 2) not null default 0,
  analyst_rating text not null default 'Hold'
    check (analyst_rating in ('Strong Buy', 'Buy', 'Hold', 'Sell')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint stocks_symbol_format check (
    symbol = upper(symbol) and symbol ~ '^[A-Z0-9]{1,10}$'
  )
);

create table if not exists public.stock_prices (
  id bigint generated by default as identity primary key,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  game_day integer not null check (game_day between 0 and 30),
  open_price numeric(12, 2) not null check (open_price > 0),
  high_price numeric(12, 2) not null check (high_price > 0),
  low_price numeric(12, 2) not null check (low_price > 0),
  close_price numeric(12, 2) not null check (close_price > 0),
  volume bigint not null default 0 check (volume >= 0),
  event_impact numeric(8, 6) not null default 0,
  created_at timestamptz not null default now(),
  unique (stock_id, game_day),
  constraint stock_prices_valid_range check (
    high_price >= greatest(open_price, close_price)
    and low_price <= least(open_price, close_price)
  )
);

create table if not exists public.market_events (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  game_day integer not null check (game_day between 1 and 30),
  source text not null,
  headline text not null,
  body text not null,
  importance text not null check (importance in ('Low', 'Medium', 'High')),
  category text not null check (
    category in (
      'earnings', 'product', 'contract', 'lawsuit', 'supply',
      'macro', 'rumor', 'partnership', 'operations'
    )
  ),
  is_accurate boolean not null default true,
  is_rumor boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.event_stock_impacts (
  event_id bigint not null references public.market_events(id) on delete cascade,
  stock_id bigint not null references public.stocks(id) on delete cascade,
  expected_impact numeric(8, 6) not null check (expected_impact between -1 and 1),
  actual_impact numeric(8, 6) not null check (actual_impact between -1 and 1),
  primary key (event_id, stock_id)
);

create table if not exists public.game_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'active'
    check (status in ('active', 'paused', 'completed')),
  current_day integer not null default 1 check (current_day between 1 and 30),
  starting_cash numeric(14, 2) not null default 2000 check (starting_cash >= 0),
  cash_balance numeric(14, 2) not null default 2000 check (cash_balance >= 0),
  portfolio_value numeric(14, 2) not null default 0 check (portfolio_value >= 0),
  net_worth numeric(14, 2) not null default 2000 check (net_worth >= 0),
  risk_score integer not null default 0 check (risk_score between 0 and 100),
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint game_sessions_valid_end check (
    ended_at is null or ended_at >= started_at
  )
);

create table if not exists public.holdings (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  stock_id bigint not null references public.stocks(id) on delete restrict,
  quantity integer not null default 0 check (quantity >= 0),
  average_purchase_price numeric(12, 2) not null default 0
    check (average_purchase_price >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (session_id, stock_id)
);

create table if not exists public.trades (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.game_sessions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  stock_id bigint not null references public.stocks(id) on delete restrict,
  game_day integer not null check (game_day between 1 and 30),
  trade_type text not null check (trade_type in ('buy', 'sell')),
  quantity integer not null check (quantity > 0),
  price_per_share numeric(12, 2) not null check (price_per_share > 0),
  total_amount numeric(14, 2)
    generated always as (round(quantity * price_per_share, 2)) stored,
  executed_at timestamptz not null default now()
);

create index if not exists stocks_sector_idx
  on public.stocks(sector) where is_active;
create index if not exists stock_prices_day_idx
  on public.stock_prices(game_day, stock_id);
create index if not exists market_events_day_idx
  on public.market_events(game_day);
create index if not exists game_sessions_user_idx
  on public.game_sessions(user_id, updated_at desc);
create index if not exists holdings_session_idx
  on public.holdings(session_id);
create index if not exists trades_session_idx
  on public.trades(session_id, executed_at desc);

